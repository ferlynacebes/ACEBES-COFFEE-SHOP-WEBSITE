<?php

/* =========================================================
   ACEBES COFFEE SHOP
   LOGOUT
========================================================= */

session_start();


/* =========================================================
   UNSET SESSION VARIABLES
========================================================= */

$_SESSION = [];


/* =========================================================
   DELETE SESSION COOKIE
========================================================= */

if (
    ini_get("session.use_cookies")
) {

    $params =
        session_get_cookie_params();

    setcookie(
        session_name(),
        "",
        time() - 42000,
        $params["path"],
        $params["domain"],
        $params["secure"],
        $params["httponly"]
    );

}


/* =========================================================
   DESTROY SESSION
========================================================= */

session_destroy();


/* =========================================================
   RETURN HOME
========================================================= */

header(
    "Location: index.php"
);

exit;

?>
